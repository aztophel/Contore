@register_ability("hustle")
class Hustle(Ability):
    async def on_modify_atk(self, ctx, owner, value: int) -> int | None:
        if owner is not ctx.user:
            return None
        return int(value * 1.5)

    async def on_accuracy_modifier(self, ctx, owner, mod: int) -> int | None:
        from ..move import MoveCategory
        gen = ctx.ruleset.number
        if owner is not ctx.user:
            return None
        if gen == 3:       # Gen 3 has no physical/special CATEGORY: Hustle keys off the move's TYPE (Showdown gen3 mod)
            if ctx.move.spec.type_name not in ("Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel"):
                return None
            return chain_mod(mod, 3277)
        if ctx.move.category is not MoveCategory.PHYSICAL:
            return None
        return chain_mod(mod, 3276 if gen == 4 else 3277)     # Gen 4: chainModify(0.8) = 3276; later [3277, 4096]


