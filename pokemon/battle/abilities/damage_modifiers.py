def _pinch_power(slug: str):
    boosted_type = PINCH_ABILITY_TYPE[slug]

    @register_ability(slug)
    class _PinchPower(Ability):
        async def on_modify_power(self, ctx, owner, power: int) -> int | None:
            if owner is not ctx.user or ctx.move.spec.type_name != boosted_type:
                return None
            if owner.vitals.hp > owner.vitals.max_hp // 3:
                return None
            return int(power * 1.5)
    _PinchPower.__name__ = slug.title() + "Ability"
    return _PinchPower


