@register_ability("sheer-force")
class SheerForce(Ability):
    """Old code guards this on the move actually HAVING a secondary effect
    to suppress (contore.py:18472-18474: `has_secondary = bool(ailment or
    flinch_chance or stat_changes)`) -- a move with no secondary at all
    gets no power boost, since there's nothing to trade away."""
    _MOVES: frozenset[str] | None = None

    @classmethod
    def _sheer_force_moves(cls) -> frozenset[str]:
        """The moves with a real `secondary`/`secondaries` block in Showdown's data (data/sheer_force_moves.json, generated by
        tests/tools/make_sheer_force_moves.js). The old `ailment or flinch_chance or stat_changes` test could not tell a
        secondary from a plain self-drop (Close Combat, Superpower, Overheat, Leaf Storm, ... were wrongly boosted AND had their
        drops suppressed) and missed confusion/other secondaries (Hurricane, Psybeam, Water Pulse, Tri Attack, ...)."""
        if cls._MOVES is None:
            import json
            from pathlib import Path
            path = Path(__file__).resolve().parents[3] / "data" / "sheer_force_moves.json"
            cls._MOVES = frozenset(json.loads(path.read_text(encoding="utf-8")))
        return cls._MOVES

    def _has_secondary(self, ctx) -> bool:
        return ctx.move.spec.slug in self._sheer_force_moves()

    async def on_modify_power(self, ctx, owner, power: int) -> int | None:
        if owner is not ctx.user or not self._has_secondary(ctx):
            return None
        return modify_raw(power, 5325)   # Showdown chainModify([5325, 4096])

    async def on_suppress_secondary_effect(self, ctx, owner) -> bool | None:
        if owner is not ctx.user or not self._has_secondary(ctx):
            return None
        return True


