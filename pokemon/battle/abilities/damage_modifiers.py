def _aura(slug: str, move_type: str):
    @register_ability(slug)
    class _Aura(Ability):
        async def on_modify_power(self, ctx, owner, power: int) -> int | None:
            if ctx.move.spec.type_name != move_type:
                return None
            # Old code checks only the two participants directly
            # (contore.py:18793-18797), not every Battler on the field.
            if owner not in (ctx.user, *ctx.targets):
                return None
            if owner is not ctx.user and attacker_breaks_mold(ctx):
                return None
            aura_break = ctx.user.identity.ability_slug == "aura-break" or any(
                t.identity.ability_slug == "aura-break" for t in ctx.targets
            )
            return modify_raw(power, 3072 if aura_break else 5448)   # Aura: x4/3, or x0.75 under Aura Break
    _Aura.__name__ = slug.title().replace("-", "") + "Ability"
    return _Aura


