@register_ability("adaptability")
class Adaptability(Ability):
    """STAB becomes x2 instead of x1.5 (Showdown `onModifySTAB`). It used to be a x4/3 POWER multiplier on top of the
    ordinary STAB, which produces the right size but rounds differently from the real thing."""
    async def on_modify_stab(self, ctx, owner, stab: float) -> float | None:
        if owner is not ctx.user or stab <= 1.0:
            return None
        return 2.0


