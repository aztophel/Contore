@register_ability("parental-bond")
class ParentalBond(Ability):
    """See NOTES_FOR_TRACK_C.md #4 -- turning one hit into two at 50%
    power on the second (Gen 6 value; later gens use 25%, but
    contore.py:18809-18810's `eff_power // 2` confirms 50% is what this
    bot actually runs) needs real support from whatever resolves a single
    move use, since it changes the hit count itself rather than a number
    within one hit. This class exists so the slug isn't silently a no-op;
    `applies()` is the check the engine is expected to call before running
    a second hit."""
    EXCLUDED_MOVES = frozenset({
        "beat-up", "bide", "counter", "dragon-rage", "endeavor", "final-gambit",
        "fling", "future-sight", "doom-desire", "mirror-coat", "metal-burst",
    })

    def applies(self, ctx, owner) -> bool:
        from ..move import MoveCategory
        return (owner is ctx.user and ctx.move.category is not MoveCategory.STATUS
                and ctx.move.slug not in self.EXCLUDED_MOVES and ctx.move.spec.max_hits <= 1)


