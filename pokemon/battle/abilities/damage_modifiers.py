@register_ability("analytic")
class Analytic(Ability):
    """x1.3 if NOBODY ELSE is still going to move this turn (Showdown `queue.willMove`, via `engine.will_move`).
    This used to compare base Speed as a stand-in, which is wrong whenever Speed boosts, paralysis, Tailwind, Trick
    Room or priority decide who actually moves last."""
    async def on_modify_power(self, ctx, owner, power: int) -> int | None:
        if owner is not ctx.user:
            return None
        for other in ctx.battle.field.all_battlers():
            if other is not owner and ctx.engine.will_move(other) is not None:
                return None
        return modify_raw(power, 5325)


